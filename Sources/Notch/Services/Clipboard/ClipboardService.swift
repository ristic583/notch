import AppKit
import Observation

struct ClipboardItem: Identifiable, Equatable {
    enum Content: Equatable {
        case text(String)
        case image(NSImage)
        case files([URL])
    }

    let id: UUID
    var content: Content
    var date: Date
    var isPinned: Bool

    init(id: UUID = UUID(), content: Content, date: Date = Date(), isPinned: Bool = false) {
        self.id = id
        self.content = content
        self.date = date
        self.isPinned = isPinned
    }

    var preview: String {
        switch content {
        case let .text(text):
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            return trimmed.replacingOccurrences(of: "\n", with: " ")
        case .image:
            return "Image"
        case let .files(urls):
            return urls.count == 1 ? urls[0].lastPathComponent : "\(urls.count) files"
        }
    }

    var symbol: String {
        switch content {
        case let .text(text): URL(string: text)?.scheme?.hasPrefix("http") == true ? "link" : "text.alignleft"
        case .image: "photo"
        case .files: "doc"
        }
    }

    /// Same content, regardless of when it was copied.
    func hasSameContent(as other: ClipboardItem) -> Bool {
        switch (content, other.content) {
        case let (.text(a), .text(b)): a == b
        case let (.files(a), .files(b)): a == b
        case let (.image(a), .image(b)): a === b
        default: false
        }
    }
}

/// History of what was copied. The pasteboard has no change notification, so
/// this polls the change counter (cheap: one integer read).
@MainActor
@Observable
final class ClipboardService {
    private(set) var items: [ClipboardItem] = []

    /// Pasteboard types that ask not to be stored (password managers use these).
    private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]
    /// Where the history was kept before it moved to a file of its own.
    static let legacyDefaultsKey = "clipboardItems"
    /// Tests bring their own.
    static var legacyDefaults = UserDefaults.standard
    /// The history on disk. Tests point this at a file of their own.
    static var storageURL = AgentActivityService.supportDirectory.appendingPathComponent("clipboard.json")

    @ObservationIgnored private let pasteboard = NSPasteboard.general
    @ObservationIgnored private var changeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var limit = 50

    init() {
        load()
    }

    func start(limit: Int) {
        self.limit = limit
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.7, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func setLimit(_ limit: Int) {
        self.limit = limit
        trim()
    }

    // MARK: - Actions

    /// Puts the item back on the pasteboard (ready to paste with ⌘V).
    func copy(_ item: ClipboardItem) {
        pasteboard.clearContents()
        switch item.content {
        case let .text(text): pasteboard.setString(text, forType: .string)
        case let .image(image): pasteboard.writeObjects([image])
        case let .files(urls): pasteboard.writeObjects(urls as [NSURL])
        }
        changeCount = pasteboard.changeCount // don't re-add what we just wrote
        if let index = items.firstIndex(where: { $0.id == item.id }), index != 0 {
            items.move(fromOffsets: IndexSet(integer: index), toOffset: 0)
            save()
        }
    }

    func togglePin(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isPinned.toggle()
        items.sort { $0.isPinned && !$1.isPinned }
        save()
    }

    func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        save()
    }

    /// Pinned entries are kept.
    func clear() {
        items.removeAll { !$0.isPinned }
        save()
    }

    // MARK: - Polling

    private func poll() {
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.privateTypes) else { return }

        guard let content = readContent() else { return }
        let item = ClipboardItem(content: content)
        if let first = items.first(where: { !$0.isPinned }), first.hasSameContent(as: item) { return }
        items.removeAll { $0.hasSameContent(as: item) && !$0.isPinned }
        items.insert(item, at: items.firstIndex { !$0.isPinned } ?? items.count)
        trim()
        save()
    }

    private func readContent() -> ClipboardItem.Content? {
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return .files(urls)
        }
        if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return .text(text)
        }
        if let image = NSImage(pasteboard: pasteboard) {
            return .image(image)
        }
        return nil
    }

    private func trim() {
        guard items.count > limit else { return }
        var kept = 0
        items.removeAll { item in
            if item.isPinned { return false }
            kept += 1
            return kept > limit
        }
    }

    // MARK: - Persistence (text and files; images stay in memory only)

    // The history can hold anything that was copied, so it lives in a file only
    // this user can read and backups skip, not in the preferences, which
    // `defaults read` prints and every backup carries.

    /// Whether the history reached the disk.
    @discardableResult
    private func save() -> Bool {
        let stored: [[String: Any]] = items.compactMap { item in
            switch item.content {
            case let .text(text):
                guard text.count < 20_000 else { return nil }
                return ["type": "text", "value": text, "date": item.date.timeIntervalSince1970, "pinned": item.isPinned]
            case let .files(urls):
                return ["type": "files", "value": urls.map(\.path), "date": item.date.timeIntervalSince1970, "pinned": item.isPinned]
            case .image:
                return nil
            }
        }
        guard let data = try? JSONSerialization.data(withJSONObject: Array(stored.prefix(60))) else { return false }
        var url = Self.storageURL
        try? FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        // Written beside the file and moved over it, so a crash never leaves half a history.
        let pending = url.appendingPathExtension("tmp")
        try? FileManager.default.removeItem(at: pending)
        guard FileManager.default.createFile(atPath: pending.path, contents: data, attributes: [.posixPermissions: 0o600]),
              rename(pending.path, url.path) == 0 else { return false }
        var values = URLResourceValues()
        values.isExcludedFromBackup = true
        try? url.setResourceValues(values)
        return true
    }

    private func load() {
        var stored = (try? Data(contentsOf: Self.storageURL))
            .flatMap { try? JSONSerialization.jsonObject(with: $0) as? [[String: Any]] } ?? []
        // History from a version that kept it in the preferences moves over once,
        // behind whatever the file already holds.
        let legacy = Self.legacyDefaults.array(forKey: Self.legacyDefaultsKey) as? [[String: Any]]
        for entry in legacy ?? [] where !stored.contains(where: { NSDictionary(dictionary: $0).isEqual(to: entry) }) {
            stored.append(entry)
        }
        items = stored.compactMap { entry in
            let date = Date(timeIntervalSince1970: entry["date"] as? Double ?? 0)
            let pinned = entry["pinned"] as? Bool ?? false
            switch entry["type"] as? String {
            case "text":
                guard let text = entry["value"] as? String else { return nil }
                return ClipboardItem(content: .text(text), date: date, isPinned: pinned)
            case "files":
                let paths = entry["value"] as? [String] ?? []
                let urls = paths.filter { FileManager.default.fileExists(atPath: $0) }.map { URL(fileURLWithPath: $0) }
                return urls.isEmpty ? nil : ClipboardItem(content: .files(urls), date: date, isPinned: pinned)
            default:
                return nil
            }
        }
        if Self.legacyDefaults.object(forKey: Self.legacyDefaultsKey) != nil, save() {
            Self.legacyDefaults.removeObject(forKey: Self.legacyDefaultsKey)
        }
    }
}
